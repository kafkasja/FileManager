import 'dart:convert';

import 'package:crypto/crypto.dart' as crypto;

/// The 4-word comparison phrase of a pairing (TASK-N3): bytes 0..3 of
/// `sha256(utf8(serverFp) ‖ utf8(clientFp))`, each mapped to a word of
/// [kFingerprintWordList]. Both fingerprints are covered, so one comparison
/// checks both directions. Order matters: swapping the arguments gives
/// other words.
List<String> fingerprintWords(String serverFp, String clientFp) {
  final digest = crypto.sha256.convert([
    ...utf8.encode(serverFp),
    ...utf8.encode(clientFp),
  ]).bytes;
  return [for (var i = 0; i < 4; i++) kFingerprintWordList[digest[i]]];
}

